package integration

// Task Day used to mean two different things depending on who wrote the row:
// plan import stored roadmap-global days, while the AI next-milestone flow
// (SaveNextMilestone) stored days relative to the task's milestone. Start and
// restart dated every task as global, so a restart dropped every generated
// milestone's tasks into the first couple of weeks — and each milestone's
// day-0 task onto today.
//
// These tests run the real SQL: legacy relative rows must still be dated from
// their milestone alongside global ones, and the one-off data fix in
// supabase/scripts must convert legacy rows to the days the server already
// schedules them on. That SaveNextMilestone now stores global days is covered
// by the sqlmock tests in database/dbcore_roadmap_generation_test.go; this
// harness's schema is too thin to run it.

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
	"time"

	"dr/server/database"
	"dr/server/types"
)

// milestoneSeed is one milestone and the stored Day of each of its tasks.
type milestoneSeed struct {
	day      int
	taskDays []int
}

// seededTask is a task row created by seedRoadmap.
type seededTask struct {
	id          string
	milestoneID string
	milestone   int // the parent milestone's Day
	day         int // the stored Day as seeded
}

// seedRoadmap creates an unstarted roadmap with the given milestones and tasks,
// all dates NULL. Tasks are returned in seed order.
func seedRoadmap(t *testing.T, userID string, milestones []milestoneSeed) (string, []seededTask) {
	t.Helper()

	var roadmapID string
	if err := testDB.Raw(
		`insert into public.roadmaps (user_id, goal) values (?, ?) returning roadmap_id`,
		userID, "Run a marathon",
	).Row().Scan(&roadmapID); err != nil {
		t.Fatalf("seed roadmap: %v", err)
	}

	var tasks []seededTask
	for _, m := range milestones {
		var milestoneID string
		if err := testDB.Raw(
			`insert into public.milestones (roadmap_id, user_id, sub_goal, day)
			 values (?, ?, 'm', ?) returning milestone_id`,
			roadmapID, userID, m.day,
		).Row().Scan(&milestoneID); err != nil {
			t.Fatalf("seed milestone day=%d: %v", m.day, err)
		}
		for _, d := range m.taskDays {
			var id string
			if err := testDB.Raw(
				`insert into public.tasks (roadmap_id, milestone_id, user_id, title, day)
				 values (?, ?, ?, 't', ?) returning task_id`,
				roadmapID, milestoneID, userID, d,
			).Row().Scan(&id); err != nil {
				t.Fatalf("seed task day=%d: %v", d, err)
			}
			tasks = append(tasks, seededTask{id: id, milestoneID: milestoneID, milestone: m.day, day: d})
		}
	}
	return roadmapID, tasks
}

// readDay fetches one task's stored Day.
func readDay(t *testing.T, taskID string) int {
	t.Helper()
	var day int
	if err := testDB.Raw(`select day from public.tasks where task_id = ?`, taskID).Row().Scan(&day); err != nil {
		t.Fatalf("read task day: %v", err)
	}
	return day
}

// mixedPlan is a three-milestone roadmap as it exists in production today: the
// first milestone's tasks are indistinguishable either way (day 0), the second
// was generated by the old SaveNextMilestone (relative days from 0), the third
// is global (import, or the fixed SaveNextMilestone).
var mixedPlan = []milestoneSeed{
	{day: 0, taskDays: []int{0, 2}},
	{day: 14, taskDays: []int{0, 3}},
	{day: 28, taskDays: []int{28, 30}},
}

// mixedPlanOffsets is where each mixedPlan task belongs, in days from the start.
var mixedPlanOffsets = []int{0, 2, 14, 17, 28, 30}

func TestStartRoadmapSchedule_DatesLegacyRelativeTasksFromTheirMilestone(t *testing.T) {
	ny, err := time.LoadLocation("America/New_York")
	if err != nil {
		t.Fatalf("load location: %v", err)
	}
	userID := createUser(t, "America/New_York")
	roadmapID, tasks := seedRoadmap(t, userID, mixedPlan)

	// Spans the 2026-11-01 DST change, so the local-timestamp arithmetic is
	// exercised on the milestone-anchored path too.
	startDate := types.ScheduleDayIn(time.Date(2026, 10, 20, 15, 0, 0, 0, time.UTC), ny)
	if err := database.StartRoadmapSchedule(roadmapID, startDate, 0, ny); err != nil {
		t.Fatalf("StartRoadmapSchedule: %v", err)
	}

	onToday := 0
	for i, task := range tasks {
		want := startDate.AddDate(0, 0, mixedPlanOffsets[i])
		got := readDate(t, "tasks", "task_id", task.id)
		if !got.Equal(want) {
			t.Errorf("task (milestone %d, day %d): date = %s, want %s",
				task.milestone, task.day, got.In(ny).Format(time.RFC3339), want.In(ny).Format(time.RFC3339))
		}
		if got.Equal(startDate) {
			onToday++
		}
	}
	// The user-visible symptom: only the first milestone's day-0 task is today.
	if onToday != 1 {
		t.Errorf("%d tasks dated on the start day, want 1", onToday)
	}
}

// globalizeTaskDaysScript is the one-off data fix with its ROLLBACK swapped for
// COMMIT, as an operator would run it after reviewing the preview.
func globalizeTaskDaysScript(t *testing.T) string {
	t.Helper()
	b, err := os.ReadFile(filepath.Join("..", "..", "supabase", "scripts", "globalize_task_days.sql"))
	if err != nil {
		t.Fatalf("read script: %v", err)
	}
	sql := string(b)
	if !strings.Contains(sql, "\nROLLBACK;") {
		t.Fatal("script no longer ends in ROLLBACK; update this test")
	}
	return strings.Replace(sql, "\nROLLBACK;", "\nCOMMIT;", 1)
}

func TestGlobalizeTaskDaysScript_ConvertsLegacyRowsAndIsIdempotent(t *testing.T) {
	userID := createUser(t, "UTC")
	roadmapID, tasks := seedRoadmap(t, userID, mixedPlan)

	script := globalizeTaskDaysScript(t)
	for run := 1; run <= 2; run++ {
		if err := testDB.Exec(script).Error; err != nil {
			t.Fatalf("run %d: %v", run, err)
		}
		for i, task := range tasks {
			if got := readDay(t, task.id); got != mixedPlanOffsets[i] {
				t.Errorf("run %d, task (milestone %d, seeded day %d): day = %d, want %d",
					run, task.milestone, task.day, got, mixedPlanOffsets[i])
			}
		}
	}

	// Converted rows must schedule exactly where the legacy ones did.
	startDate := types.ScheduleDayIn(time.Date(2026, 9, 22, 12, 0, 0, 0, time.UTC), time.UTC)
	if err := database.StartRoadmapSchedule(roadmapID, startDate, 0, time.UTC); err != nil {
		t.Fatalf("StartRoadmapSchedule: %v", err)
	}
	for i, task := range tasks {
		want := startDate.AddDate(0, 0, mixedPlanOffsets[i])
		if got := readDate(t, "tasks", "task_id", task.id); !got.Equal(want) {
			t.Errorf("task %d: date = %s, want %s", i, got.UTC(), want.UTC())
		}
	}
}
